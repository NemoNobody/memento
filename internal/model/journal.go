package model

import (
	"strings"
	"time"
)

// Journal operations. The journal is a log of accepted values: every write
// that changed (or established) a fact's value appends op=write. op=rediscovery
// records a re-confirmation of the same value (memento_patch reverify): the
// fact's observed_at moves and the writer joins confirmed_by, so the event (who,
// when) belongs in the log. op=retire marks the entry written for a
// verified→obsolete transition, so "when and by whom was this retired" is a
// query, not an inference from notes text.
const (
	OpWrite       = "write"
	OpRediscovery = "rediscovery"
	OpRetire      = "retire"
)

// ValidOp reports whether op is a known journal operation.
func ValidOp(op string) bool {
	switch strings.ToLower(op) {
	case OpWrite, OpRediscovery, OpRetire:
		return true
	}
	return false
}

// JournalEntry is one accepted observation of a fact key, stored in the
// journal index (one doc per entry, op_type=create). The journal is append-only:
// entries are immutable after the fact, corrections append a new entry, and
// "history" is a query over this log. Entry ids are generated by OpenSearch;
// the fact's main doc keeps current_ref = the entry id of its current value,
// so "the journal contains the current value" does not depend on write order.
type JournalEntry struct {
	// FactKey is the fact key this entry observes; fact_id is kept so entries
	// survive key renames and stay groupable.
	FactKey  string `json:"fact_key"`
	FactID   string `json:"fact_id,omitempty"`
	Project  string `json:"project,omitempty"`
	Category string `json:"category,omitempty"`
	Op       string `json:"op"`
	Value    string `json:"value"`
	Notes    string `json:"notes,omitempty"`
	Source   string `json:"source,omitempty"`
	// Keywords is the tag set as of this accepted value. Tags themselves are a
	// stored qualifier (a tag-only change is a touch, not a journal entry), so
	// the previous set stays recoverable from the entry that carried it.
	Keywords  []string  `json:"keywords,omitempty"`
	CreatedAt time.Time `json:"created_at"`

	// Authorship of this entry: who appended it (self-reported labels, see
	// model.Fact). Each entry names its own writer — the journal is a log,
	// and "who wrote this version" is a per-entry fact.
	Author       string `json:"author,omitempty"`
	AuthorSource string `json:"author_source,omitempty"`
	Model        string `json:"model,omitempty"`
	Host         string `json:"host,omitempty"`
	Session      string `json:"session,omitempty"`
}

// NewJournalEntry builds an entry for an accepted value at time now (UTC).
func NewJournalEntry(factKey, factID, project, category, op, value, notes, source string, now time.Time) *JournalEntry {
	return &JournalEntry{
		FactKey:   factKey,
		FactID:    factID,
		Project:   project,
		Category:  category,
		Op:        op,
		Value:     value,
		Notes:     notes,
		Source:    source,
		CreatedAt: now.UTC(),
	}
}

// HistoryInfo is the compact per-key journal summary for agents: is this
// fact's value confirmed by re-discovery, and how much churn has it seen.
//
// Counts are LOWER BOUNDS: an admin pruning old journal indices deletes
// entries without the app knowing, so first_at and counts describe the
// surviving journal, not the full lifetime.
type HistoryInfo struct {
	Key           string     `json:"key"`
	Writes        int        `json:"writes"`
	Rediscoveries int        `json:"rediscoveries"`
	FirstAt       *time.Time `json:"first_at,omitempty"`
	LastAt        *time.Time `json:"last_at,omitempty"`
	Category      string     `json:"category,omitempty"`
	CurrentRef    string     `json:"current_ref,omitempty"`
}
